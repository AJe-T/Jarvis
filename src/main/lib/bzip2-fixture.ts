/** The 230 kB the big fixture holds: short text lines and, now and then, a run of one byte (up to 299 long). */
export function fixtureData(): Uint8Array {
  let seed = 1;
  const next = (): number => (seed = (seed * 48271) % 2147483647);
  const out: number[] = [];
  while (out.length < 230_000) {
    if (next() % 25 === 0) {
      const byte = next() % 256;
      const n = next() % 300;
      for (let j = 0; j < n; j++) out.push(byte);
    } else for (const c of `jarvis hey summer ${next() % 1000}\n`) out.push(c.charCodeAt(0));
  }
  return Uint8Array.from(out.slice(0, 230_000));
}

